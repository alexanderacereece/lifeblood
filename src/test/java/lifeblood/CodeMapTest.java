package lifeblood;

import static org.junit.jupiter.api.Assertions.fail;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import lifeblood.SourceTree.SourceFile;
import org.junit.jupiter.api.Test;

/**
 * Keeps docs/code-map.md, the list of every package and class with what each is for, matching the code. The map is
 * written from the package-info and class doc comments, so it's never edited by hand: when it's out of date, this test
 * rewrites it and fails once, so the new map gets noticed and committed with the change.
 */
class CodeMapTest {
	static final Path MAP = Path.of("docs/code-map.md");

	@Test
	void codeMapIsCurrent() throws IOException {
		String map = render(SourceTree.read(SourceTree.MAIN));
		String current = Files.exists(MAP) ? Files.readString(MAP, StandardCharsets.UTF_8).replace("\r\n", "\n") : "";
		if (!map.equals(current)) {
			Files.writeString(MAP, map, StandardCharsets.UTF_8);
			fail("docs/code-map.md was out of date and has been rewritten from the doc comments. Build again, and commit it with the change.");
		}
	}

	static String render(List<SourceFile> files) {
		StringBuilder out = new StringBuilder();
		out.append("# Code map\n\n");
		out.append("Every package and class in `src/main/java/lifeblood`, with the first sentence of its doc comment. ");
		out.append("**Generated by `CodeMapTest` on every build; don't edit it by hand.** To change a line, change the doc comment.\n\n");
		out.append("Search this before writing anything new: if something close already exists, use it or extend it. ");
		out.append("How the pieces fit together is in [architecture.md](architecture.md).\n");
		SourceTree.packages(files).forEach((name, info) -> {
			String folder = name.equals("lifeblood") ? "" : name.substring("lifeblood.".length()).replace('.', '/');
			out.append("\n## `").append(folder.isEmpty() ? "lifeblood" : folder).append("`\n\n");
			if (info != null) {
				out.append(SourceTree.firstSentence(info.doc())).append("\n\n");
			}

			for (SourceFile file : files) {
				if (file.packageName().equals(name) && !file.isPackageInfo()) {
					String link = "../" + file.path().toString().replace('\\', '/');
					out.append("- [`").append(file.name()).append("`](").append(link).append(")");
					String sentence = SourceTree.firstSentence(file.doc());
					if (!sentence.isEmpty()) {
						out.append(": ").append(sentence);
					}

					out.append('\n');
				}
			}
		});
		return out.toString();
	}
}
